"""Deterministic static PWA resources; imported by convert_bible.py."""
import hashlib
import json
from bible_sources import ROOT


def offline_manifest(generated_assets: dict) -> bytes:
    assets={p:p.read_bytes() for p in (ROOT/'assets').rglob('*') if p.is_file()}
    assets.update(generated_assets)
    fingerprint=hashlib.sha256()
    inputs=dict(assets)
    for folder,pattern in [('lib','*.dart'),('web','*.js')]:
        inputs.update({p:p.read_bytes() for p in (ROOT/folder).rglob(pattern) if p.name!='reader_offline_assets.js'})
    for name in ['pubspec.yaml','pubspec.lock','web/index.html','web/manifest.json']:
        p=ROOT/name;inputs[p]=p.read_bytes()
    for path,data in sorted(inputs.items()):
        if path.suffix in {'.dart','.js','.json','.md','.yaml','.lock','.html'}:
            data=data.replace(b'\r\n',b'\n')
        fingerprint.update(path.relative_to(ROOT).as_posix().encode('utf8')+b'\0'+data)
    manifest={'version':fingerprint.hexdigest()[:20],
              'files':sorted('assets/'+p.relative_to(ROOT).as_posix() for p in assets)}
    return ('// Generated by python tools/convert_bible.py; do not edit.\nself.READER_OFFLINE = '+json.dumps(manifest,separators=(',',':'))+';\n').encode('utf8')
