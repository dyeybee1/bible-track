// Run AFTER Flutter: node tools/build_pwa.cjs [build/web]
// Requires only Node built-ins and the finished build directory.
'use strict';
const fs = require('node:fs');
const path = require('node:path');
const {createHash} = require('node:crypto');
const generated = new Set(['reader_service_worker.js', 'reader_offline_assets.js', 'version.json', 'flutter_service_worker.js']);
const marker = /\/\* PWA_BUILD_START \*\/[\s\S]*?\/\* PWA_BUILD_END \*\//g;
const canonical = '/* PWA_BUILD_START */ null /* PWA_BUILD_END */';
const sha256 = bytes => createHash('sha256').update(bytes).digest('hex');

function buildPwa(directory = 'build/web') {
  const root = path.resolve(directory);
  for (const name of ['index.html', 'main.dart.js', 'flutter_bootstrap.js', 'pwa_update.js', 'reader_service_worker.js', 'assets/FontManifest.json']) {
    if (!fs.statSync(path.join(root, name), {throwIfNoEntry:false})?.isFile()) throw new Error('Build Flutter web first; missing ' + name);
  }
  const workerPath = path.join(root, 'reader_service_worker.js');
  const source = fs.readFileSync(workerPath, 'utf8').replace(/\r\n/g, '\n');
  if ([...source.matchAll(marker)].length !== 1) throw new Error('Missing unique PWA build marker');
  const template = source.replace(marker, canonical);
  const files = [];
  function walk(folder, prefix = '') {
    for (const entry of fs.readdirSync(folder, {withFileTypes:true})) {
      const name = prefix + entry.name;
      if (entry.isSymbolicLink()) throw new Error('Symlink in web output: ' + name);
      if (entry.isDirectory()) walk(path.join(folder, entry.name), name + '/');
      else if (entry.isFile() && !generated.has(name)) files.push(name);
    }
  }
  walk(root);
  files.sort();
  const resources = Object.fromEntries(files.map(name => [name, sha256(fs.readFileSync(path.join(root, name)))]));
  // Metadata cannot hash itself; worker behavior is hashed as a null template.
  const version = sha256(JSON.stringify({worker:sha256(template), resources}));
  const manifest = {version, files, resources};
  fs.writeFileSync(workerPath, template.replace(marker, '/* PWA_BUILD_START */ ' + JSON.stringify(manifest) + ' /* PWA_BUILD_END */'));
  fs.writeFileSync(path.join(root, 'reader_offline_assets.js'), '// Generated by tools/build_pwa.cjs after Flutter.\nself.READER_OFFLINE = ' + JSON.stringify(manifest) + ';\n');
  const versionPath = path.join(root, 'version.json');
  const previous = fs.existsSync(versionPath) ? JSON.parse(fs.readFileSync(versionPath, 'utf8')) : {};
  const {buildHash: unusedHash, precache: unusedPrecache, ...flutterVersion} = previous;
  fs.writeFileSync(versionPath, JSON.stringify({...flutterVersion, buildHash:version, precache:files}, null, 2) + '\n');
  return manifest;
}
module.exports = {buildPwa};
if (require.main === module) {
  try {
    const result = buildPwa(process.argv[2]);
    console.log('PWA release ' + result.version + ': ' + result.files.length + ' content-hashed precache files.');
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
